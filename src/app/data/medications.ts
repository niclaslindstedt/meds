// The bundled medication catalog: the names people actually have on their
// shelf (Swedish market — brand names and common generics, the vocabulary
// FASS taught everyone), each with the strengths it is commonly dispensed
// in. The Add form's autocomplete and dose chips read this and nothing else.
//
// **This file is data, and it never leaves the device.** The app's one rule
// (see AGENTS.md) forbids a lookup API — what someone types into a
// medication field is exactly the byte that must not reach a server — so the
// catalog ships in the bundle instead, behind `import()` so the main chunk
// does not carry it. FASS itself has no public API and its content is not
// openly licensed, which is why this is a curated seed list rather than an
// extract: names and strengths are facts, and this file states them in its
// own words. A fuller list can be regenerated from Läkemedelsverket's open
// LiiV/NPL product data and dropped in here — the shape is deliberately
// trivial to generate into.
//
// Curation rule: common, currently-dispensed medications only, one entry per
// name as printed on the box (a brand and its generic are two entries when
// both are common). Strengths are the usual per-dose ones, lowest first.
// This is an *aid to typing*, not a formulary: an unlisted medication is
// typed by hand and works exactly the same.

/** One catalog entry: the name on the box, and its common strengths. */
export type CatalogEntry = { name: string; strengths: string[] };

function m(name: string, ...strengths: string[]): CatalogEntry {
  return { name, strengths };
}

